import { ApiProperty } from '@nestjs/swagger';
import { IsEmail, IsNotEmpty, IsOptional, IsString, Length, Matches, MaxLength, MinLength } from 'class-validator';

export class LoginDto {
  @ApiProperty({ example: 'admin@example.org' })
  @IsEmail()
  @MaxLength(254)
  email!: string;

  @ApiProperty({ description: 'Account password' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  password!: string;

  @ApiProperty({ required: false, description: '6-digit TOTP code when MFA is enabled' })
  @IsOptional()
  @Matches(/^\d{6}$/, { message: 'totp must be 6 digits' })
  totp?: string;
}

export class RefreshDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  refreshToken!: string;
}

export class MfaCodeDto {
  @ApiProperty({ example: '123456' })
  @Matches(/^\d{6}$/, { message: 'code must be 6 digits' })
  code!: string;
}

export class PasswordChangeDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  currentPassword!: string;

  @ApiProperty({ minLength: 12 })
  @IsString()
  @MinLength(12)
  @MaxLength(200)
  newPassword!: string;
}

export class DisableMfaDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  password!: string;
}

export class CreateAccountDto {
  @ApiProperty()
  @IsEmail()
  email!: string;

  @ApiProperty()
  @IsString()
  @Length(2, 80)
  displayName!: string;

  @ApiProperty({ description: 'One of the six administration roles' })
  @IsString()
  role!: string;

  @ApiProperty({ minLength: 12, description: 'Generated by the caller, never a default value' })
  @IsString()
  @MinLength(12)
  @MaxLength(200)
  password!: string;
}

export class TransitionDto {
  @ApiProperty({ example: 'UNDER_VERIFICATION' })
  @IsString()
  to!: string;

  @ApiProperty({ required: false, maxLength: 500 })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  note?: string;
}
